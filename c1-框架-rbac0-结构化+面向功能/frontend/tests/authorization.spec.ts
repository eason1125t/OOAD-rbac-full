// 用两个相互隔离的浏览器会话检验管理端和业务端的真实 HTTP 链路。
import { expect, test, type Page } from '@playwright/test'

/** 通过登录页建立独立会话。 */
async function login(page: Page, username: string, password: string) {
  await page.goto('/')
  await page.getByLabel('用户名').fill(username)
  await page.getByLabel('密码').fill(password)
  await page.getByRole('button', { name: '登录', exact: true }).click()
}

test('C1-06 管理员授撤权对同一员工会话立即生效', async ({ browser }, testInfo) => {
  const password = process.env.RBAC_DEMO_PASSWORD
  expect(password, '请配置隔离环境中的演示密码').toBeTruthy()
  const adminContext = await browser.newContext()
  const employeeContext = await browser.newContext()
  try {
    const admin = await adminContext.newPage()
    const worker = await employeeContext.newPage()
    await login(admin, 'super-admin', password!)
    await login(worker, 'engineering-employee', password!)
    await expect(admin).toHaveURL(/\/admin\/$/)
    await expect(worker).toHaveURL(/\/business\/demo-engineering-app\/$/)
    await expect(admin.getByRole('heading', { name: '管理总览' })).toBeVisible()
    await admin.screenshot({ path: testInfo.outputPath('overview.png'), fullPage: true })
    const navigation = admin.getByRole('navigation', { name: '管理导航' })
    await navigation.getByRole('link', { name: '部门目录' }).click()
    await expect(admin.getByRole('columnheader', { name: '部门经理' })).toBeVisible()
    await navigation.getByRole('link', { name: '角色管理' }).click()
    const roleName = `浏览器验收角色 ${Date.now()}`
    await admin.getByRole('button', { name: '新增角色' }).click()
    const editor = admin.getByRole('dialog')
    await editor.getByRole('textbox', { name: '名称' }).fill(roleName)
    await editor.getByRole('button', { name: '确认' }).click()
    const newRole = admin.getByRole('row').filter({ hasText: roleName })
    await expect(newRole).toBeVisible()
    await newRole.getByRole('button', { name: '编辑' }).click()
    await editor.getByRole('textbox', { name: '名称' }).fill(`${roleName} 已编辑`)
    await editor.getByRole('button', { name: '确认' }).click()
    await expect(newRole).toContainText('已编辑')
    await newRole.getByRole('button', { name: '删除' }).click()
    await editor.getByRole('button', { name: '确认' }).click()
    await expect(newRole).toHaveCount(0)
    await expect(navigation.getByRole('link', { name: '授权分配' })).toHaveCount(0)
    await navigation.getByRole('link', { name: '权限管理' }).click()
    await admin.getByRole('link', { name: 'Excel 原表清单' }).click()
    await expect(admin.getByRole('region', { name: '功能权限清单' })).toBeVisible()
    await expect(admin.getByRole('button', { name: '新增权限' })).toHaveCount(0)
    await admin.getByRole('link', { name: '生效权限配置' }).click()
    await admin.getByRole('button', { name: '新增权限' }).click()
    await expect(editor.getByRole('combobox', { name: '业务系统' }).getByRole('option', {
      name: /示例工程申请系统/,
    })).toHaveCount(1)
    await editor.getByRole('button', { name: '取消' }).click()
    await admin.getByRole('row').filter({ hasText: '工程申请审批' }).getByRole('button', { name: '组织策略' }).click()
    const policy = admin.getByRole('dialog', { name: '组织策略' })
    await policy.getByRole('combobox', { name: '目标组织' }).selectOption({ label: '示例工程部（部门）' })
    await policy.getByRole('button', { name: '停用', exact: true }).click()
    await policy.getByRole('button', { name: '确认停用' }).click()
    await policy.getByRole('button', { name: '重新开放' }).click()
    await policy.getByRole('combobox', { name: '待重授角色' }).selectOption({ label: '示例工程审批员' })
    await policy.getByRole('button', { name: '重授角色' }).click()
    await expect(policy.getByText('已重授 1 个角色')).toBeVisible()
    await policy.getByRole('button', { name: '关闭' }).click()
    await navigation.getByRole('link', { name: '员工管理' }).click()
    const openEmployeeRoles = async () => {
      await navigation.getByRole('link', { name: '员工管理' }).click()
      await admin.getByRole('row').filter({ hasText: 'engineering-employee' })
        .getByRole('button', { name: '管理角色' }).click()
    }
    const sessionCookie = (await employeeContext.cookies()).find(cookie => cookie.name === 'SESSION')
    expect(sessionCookie).toBeDefined()
    const switcher = worker.getByRole('combobox', { name: '当前系统' })
    await expect(switcher.getByRole('option', { name: '权限管理平台' })).toHaveCount(0)
    await switcher.selectOption('/business/demo-company-app/')
    await expect(worker).toHaveURL(/\/business\/demo-company-app\/$/)
    await worker.getByRole('combobox', { name: '当前系统' }).selectOption('/business/demo-engineering-app/')
    await expect(worker).toHaveURL(/\/business\/demo-engineering-app\/$/)
    const employeeRoles = admin.getByRole('dialog', { name: '管理角色' })
    const rolePermissions = admin.getByRole('dialog', { name: '管理权限' })
    await navigation.getByRole('link', { name: '角色管理' }).click()
    await admin.getByRole('row').filter({ hasText: '示例工程审批员' }).getByRole('button', { name: '管理权限' }).click()
    const permissionSelect = rolePermissions.getByRole('combobox', { name: '待授予权限' })
    const permissionId = await permissionSelect.locator('option').filter({ hasText: '工程申请审批' })
      .evaluate(option => (option as HTMLOptionElement).value)
    await expect(rolePermissions.getByRole('button', { name: '撤销权限' })).toBeVisible()
    await rolePermissions.getByRole('button', { name: '撤销权限' }).click()
    await expect(rolePermissions.getByText('暂无权限分配')).toBeVisible()
    await permissionSelect.selectOption(permissionId)
    await rolePermissions.getByRole('button', { name: '授予权限' }).click()
    await expect(rolePermissions.getByRole('button', { name: '撤销权限' })).toBeVisible()
    await rolePermissions.getByRole('button', { name: '关闭' }).click()
    // 删除角色权限会同时清理显式重授，重建关系后恢复该组织的授权。
    await navigation.getByRole('link', { name: '权限管理' }).click()
    await admin.getByRole('row').filter({ hasText: '工程申请审批' }).getByRole('button', { name: '组织策略' }).click()
    await policy.getByRole('combobox', { name: '目标组织' }).selectOption({ label: '示例工程部（部门）' })
    await policy.getByRole('combobox', { name: '待重授角色' }).selectOption({ label: '示例工程审批员' })
    await policy.getByRole('button', { name: '重授角色' }).click()
    await expect(policy.getByText('已重授 1 个角色')).toBeVisible()
    await policy.getByRole('button', { name: '关闭' }).click()
    await openEmployeeRoles()

    await employeeRoles.getByRole('button', { name: '撤销角色' }).click()
    await expect(employeeRoles.getByText('暂无角色分配')).toBeVisible()
    const pending = worker.getByRole('row').filter({ hasText: '待审批' })
    await expect(pending.nth(1)).toBeVisible()
    const receipt = worker.getByRole('complementary', { name: '审批结果' })
    await pending.first().getByRole('button', { name: '审批', exact: true }).click()
    await expect(receipt).toContainText('拒绝')
    await expect(receipt).toContainText('未执行')

    await employeeRoles.getByLabel('待授予角色').selectOption({ label: '示例工程审批员' })
    await employeeRoles.getByRole('button', { name: '授予角色' }).click()
    await expect(employeeRoles.getByRole('button', { name: '撤销角色' })).toBeVisible()
    await admin.screenshot({ path: testInfo.outputPath('admin.png') })
    await pending.first().getByRole('button', { name: '审批', exact: true }).click()
    await expect(receipt).toContainText('通过')
    await expect(receipt).toContainText('成功')

    await employeeRoles.getByRole('button', { name: '撤销角色' }).click()
    await expect(employeeRoles.getByText('暂无角色分配')).toBeVisible()
    const deniedRequest = pending.first()
    const deniedResponse = worker.waitForResponse(response =>
      response.request().method() === 'POST' && response.url().endsWith('/approve'))
    await deniedRequest.getByRole('button', { name: '审批', exact: true }).click()
    expect((await deniedResponse).status()).toBe(403)
    await expect(receipt).toContainText('拒绝')
    await expect(receipt).toContainText('未执行')
    await expect(worker.getByText('engineering-employee', { exact: true })).toBeVisible()
    expect((await employeeContext.cookies()).find(cookie => cookie.name === 'SESSION')?.value).toBe(sessionCookie?.value)
    await worker.screenshot({ path: testInfo.outputPath('business.png') })
    await worker.setViewportSize({ width: 390, height: 844 })
    await expect(receipt).toBeVisible()
    expect(await worker.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
    await employeeRoles.getByLabel('待授予角色').selectOption({ label: '示例工程审批员' })
    await employeeRoles.getByRole('button', { name: '授予角色' }).click()
    await expect(employeeRoles.getByRole('button', { name: '撤销角色' })).toBeVisible()
  } finally {
    await adminContext.close()
    await employeeContext.close()
  }
})
